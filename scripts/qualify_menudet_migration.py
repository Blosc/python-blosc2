"""Exchange Menudet fixtures between independently installed wheels.

Run ``write DEST`` with the writer wheel and ``check DEST`` with the reader
wheel. Run in both directions to qualify 4.17 and next. The v1 input must be
the committed fixture generated by the released 4.16.1 wheel.
"""

import argparse
import contextlib
import json
import shutil
from dataclasses import dataclass
from pathlib import Path

import numpy as np

import blosc2

V1 = Path(__file__).resolve().parents[1] / "tests" / "data" / "legacy_menudet_v1"


@dataclass
class Row:
    x: float = blosc2.field(blosc2.float32(), default=0)


@blosc2.menudet(jit=False)
def shifted(x: np.float32):
    return x + 2.0


def write(directory):
    directory.mkdir()
    for name in ("kernel.b2nd", "x.b2nd"):
        shutil.copyfile(V1 / name, directory / name)
    with contextlib.chdir(directory):
        source = Path("kernel.b2nd")
        original = source.read_bytes()
        legacy = blosc2.open(source, mode="r")
        assert legacy.schunk.meta["b2o"]["version"] == 1
        np.testing.assert_array_equal(legacy[:], np.array([1, 27, 125, 343], dtype="float64"), strict=True)
        manifest = json.loads(legacy.kernel.to_json())
        manifest["semantics"]["integer_powers"] = "multiply"
        explicit = blosc2.MenudetKernel.from_json(json.dumps(manifest), jit=False)
        explicit.lazy(legacy.inputs, shape=legacy.shape, partitions=legacy.partitions).save(
            "policy.b2nd", mode="w"
        )
        legacy.save("migrated.b2nd", mode="w")
        assert source.read_bytes() == original
        x = blosc2.open("x.b2nd", mode="r")
        annotated = shifted(x)
        annotated.save("annotated.b2nd", mode="w")
        Path("annotated.b2frame").write_bytes(annotated.to_cframe())
        with blosc2.CTable(Row, new_data={"x": x[:]}, create_summary_index=False) as table:
            kernel = shifted.specialize(x)
            table.add_computed_column("shifted", kernel, inputs={"x": "x"})
            table.save("computed.b2d")


def check(directory):
    migrated = blosc2.open(directory / "migrated.b2nd", mode="r")
    assert migrated.schunk.meta["b2o"] == {"version": 2, "kind": "menudet"}
    recipe = migrated.kernel.to_recipe()
    assert recipe["language_version"] == "0.1"
    assert recipe["input_constraints"] == {"x": {"dtype": "float32"}}
    assert recipe["output"] == {"dtype": "float64"}
    assert recipe["cardinality"] == "elementwise"
    assert [item["category"] for item in recipe["constants"]] == ["weak", "typed_scalar"]
    assert migrated.partitions == (2,)
    expected = np.array([1, 27, 125, 343], dtype="float64")
    np.testing.assert_array_equal(migrated[:], expected, strict=True)
    policy = blosc2.open(directory / "policy.b2nd", mode="r")
    assert policy.kernel.to_recipe()["semantics"] == {"integer_powers": "multiply"}
    np.testing.assert_array_equal(policy[:], expected, strict=True)
    annotated = blosc2.open(directory / "annotated.b2nd", mode="r")
    # A detached frame has no carrier location; resolve its relative operand
    # the same way a caller does after moving the entire fixture directory.
    with contextlib.chdir(directory):
        frame = blosc2.from_cframe(Path("annotated.b2frame").read_bytes())
        for obj in (annotated, frame):
            recipe = obj.kernel.to_recipe()
            assert recipe["language_version"] == "0.2"
            assert "x: float32" in recipe["source"]
            np.testing.assert_array_equal(obj[:], np.arange(2, 6, dtype="float32"), strict=True)
    with blosc2.CTable.open(str(directory / "computed.b2d"), mode="r") as table:
        np.testing.assert_array_equal(table["shifted"][:], np.arange(2, 6, dtype="float32"), strict=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("write", "check"))
    parser.add_argument("directory", type=Path)
    args = parser.parse_args()
    print(f"{args.action}: Python-Blosc2 {blosc2.__version__} from {blosc2.__file__}")
    print(f"native extension: {blosc2.blosc2_ext.__file__}")
    (write if args.action == "write" else check)(args.directory.resolve())


if __name__ == "__main__":
    main()
